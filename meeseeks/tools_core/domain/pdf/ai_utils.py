load_dotenv()


def get_client():
    """Get authenticated Gemini client."""
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise ValueError("GEMINI_API_KEY not found in environment variables")
    return genai.Client(api_key=api_key)


def _handle_api_error(e: Exception) -> None:
    """Handle common Gemini API errors with helpful messages."""
    error_msg = str(e).lower()
    if "quota" in error_msg or "billing" in error_msg or "payment" in error_msg:
        raise RuntimeError(
            "Gemini API Error: This tool requires a PAID API key with billing enabled.\n"
            "Free tier keys do not support image generation. Please:\n"
            "1. Visit https://aistudio.google.com/api-keys\n"
            "2. Enable billing on your Google Cloud project\n"
            f"Original error: {e}"
        )
    elif "api key" in error_msg or "authentication" in error_msg or "unauthorized" in error_msg:
        raise RuntimeError(
            "Gemini API Error: Invalid API key.\n"
            "Please check that your GEMINI_API_KEY environment variable is set correctly.\n"
            f"Original error: {e}"
        )
    else:
        raise RuntimeError(f"Gemini API Error: {e}")


def generate_slide(
    user_prompt: str,
    target_image: Optional[Image.Image] = None,
    style_reference_images: Optional[List[Image.Image]] = None,
    full_text_context: str = "",
    resolution: str = "4K",
    enable_search: bool = False
) -> Tuple[Image.Image, Optional[str]]:
    """
    Generate or edit a slide image using Gemini.
    
    This unified function handles both new slide generation and editing:
    - If target_image is provided: Edit existing slide
    - If target_image is None: Generate new slide from scratch
    
    Args:
        user_prompt: The generation/edit prompt
        target_image: Optional existing image to edit
        style_reference_images: Optional style reference images
        full_text_context: Optional document context
        resolution: Image resolution ("4K", "2K", etc.)
        enable_search: Whether to enable Google Search grounding
        
    Returns:
        Tuple of (generated PIL Image, optional text response)
    """
    client = get_client()
    
    # Build prompt parts
    prompt_parts = [user_prompt]
    
    if target_image:
        prompt_parts.append(target_image)
    
    if style_reference_images:
        prompt_parts.append("Match the visual style (fonts, colors, layout) of these reference images:")
        prompt_parts.extend(style_reference_images)
    
    if full_text_context:
        prompt_parts.append(f"DOCUMENT CONTEXT:\n{full_text_context}\n")
    
    # Build config
    config = types.GenerateContentConfig(
        response_modalities=['TEXT', 'IMAGE'],
        image_config=types.ImageConfig(image_size=resolution)
    )
    if enable_search:
        config.tools = [{"google_search": {}}]
    
    # Call API
    try:
        response = client.models.generate_content(
            model=IMAGE_MODEL,
            contents=prompt_parts,
            config=config
        )
    except Exception as e:
        _handle_api_error(e)
    
    # Extract response
    generated_image = None
    response_text = None
    
    if response.candidates and response.candidates[0].content.parts:
        for part in response.candidates[0].content.parts:
            if part.inline_data:
                from io import BytesIO
                generated_image = Image.open(BytesIO(part.inline_data.data))
            elif part.text:
                response_text = part.text
    
    if not generated_image:
        raise RuntimeError("No image generated by the model.")
    
    return generated_image, response_text


