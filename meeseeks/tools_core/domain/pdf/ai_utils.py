def semantic_search_pages(
    page_texts: Dict[int, str],
    query: str,
    page_images: Optional[Dict[int, Image.Image]] = None,
    top_k: int = 5
) -> List[Dict[str, Any]]:
    """
    Performs semantic search across PDF pages using Gemini.
    
    Args:
        page_texts: Dict mapping page number (1-indexed) to extracted text
        query: The search query
        page_images: Optional dict mapping page number to PIL Image for visual search
        top_k: Maximum number of results to return
    
    Returns:
        List of dicts with keys: page, relevance, explanation, snippet
    """
    from . import prompts
    
    # Build pages content
    pages_content = ""
    for page_num in sorted(page_texts.keys()):
        text = page_texts[page_num]
        if len(text) > 1500:
            text = text[:1500] + "...[truncated]"
        pages_content += f"\n--- PAGE {page_num} ---\n{text}\n"
    
    prompt = prompts.SEMANTIC_SEARCH_PROMPT.format(
        query=query,
        top_k=top_k,
        pages_content=pages_content
    )
    
    # Build content list
    contents = [prompt]
    if page_images:
        contents.append("\nVisual content from pages:")
        for page_num in sorted(page_images.keys()):
            contents.append(f"\nPage {page_num} visual:")
            contents.append(page_images[page_num])
    
    # Call API
    client = get_client()
    config = types.GenerateContentConfig(
        response_modalities=['TEXT'],
        temperature=0.1,
    )
    
    try:
        response = client.models.generate_content(
            model=DEFAULT_MODEL,
            contents=contents,
            config=config
        )
    except Exception as e:
        error_msg = str(e).lower()
        if "api key" in error_msg or "authentication" in error_msg:
            raise RuntimeError(f"Gemini API Error: Invalid API key. {e}")
        raise RuntimeError(f"Gemini API Error: {e}")
    
    # Extract and parse response
    response_text = ""
    if response.candidates and response.candidates[0].content.parts:
        for part in response.candidates[0].content.parts:
            if part.text:
                response_text = part.text
                break
    
    result = clean_json_response(response_text)
    
    if isinstance(result, list):
        return result[:top_k]
    elif isinstance(result, dict) and "error" not in result:
        return []
    return []


def describe_page(page_image: Image.Image, page_text: str = "") -> str:
    """
    Gets a detailed description of a PDF page using Gemini vision.
    
    Args:
        page_image: PIL Image of the page
        page_text: Optional extracted text from the page
        
    Returns:
        Detailed description of the page content
    """
    from . import prompts
    
    client = get_client()
    
    contents = [prompts.DESCRIBE_PAGE_PROMPT, page_image]
    if page_text:
        contents.append(f"\nExtracted text for reference:\n{page_text[:1000]}")
    
    config = types.GenerateContentConfig(
        response_modalities=['TEXT'],
        temperature=0.3,
    )
    
    try:
        response = client.models.generate_content(
            model=DEFAULT_MODEL,
            contents=contents,
            config=config
        )
    except Exception as e:
        raise RuntimeError(f"Gemini API Error: {e}")
    
    if response.candidates and response.candidates[0].content.parts:
        for part in response.candidates[0].content.parts:
            if part.text:
                return part.text
    
    return "Could not describe page."
